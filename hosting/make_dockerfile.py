"""Produce the cloud Dockerfile from the upstream packaging and a pinned toolkit."""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
revision = sys.argv[1]
if not re.fullmatch(r'[0-9a-f]{40}', revision):
    raise SystemExit('Pass the full toolkit commit SHA')
source_stage = f'''# Generated by hosting/make_dockerfile.py. Do not edit manually.
FROM alpine:3.22 AS nova
RUN apk add --no-cache curl tar && mkdir /source && \\
    curl -fsSL https://codeload.github.com/vestergaardn/ldraw-nova/tar.gz/{revision} \\
    | tar -xz -C /source --strip-components=1
'''
dockerfile = (root / 'Dockerfile').read_text()
dockerfile = dockerfile.replace('ENV DEBIAN_FRONTEND=noninteractive',
    'ENV DEBIAN_FRONTEND=noninteractive\nENV UV_DEFAULT_INDEX=https://pypi.org/simple UV_INDEX_URL=https://pypi.org/simple')
dockerfile = re.sub(r'^COPY --from=nova (.+?) /opt/ldraw-nova/(.*)$',
    lambda match: 'COPY --from=nova ' + ' '.join('/source/' + token for token in match[1].split())
    + ' /opt/ldraw-nova/' + match[2], dockerfile, flags=re.M)
dockerfile = re.sub(r'^(ENTRYPOINT|CMD|VOLUME|EXPOSE) .*\n?', '', dockerfile, flags=re.M)
# Modal's Dockerfile builder does not expand ARGs in local COPY sources.
arguments = dict(re.findall(r'^ARG (\w+)=(.+)$', dockerfile, re.M))
dockerfile = '\n'.join(re.sub(r'\$\{(\w+)\}', lambda m: arguments[m[1]], line)
    if line.startswith('COPY ') else line for line in dockerfile.split('\n'))
dockerfile += '\nRUN ln -sf /usr/bin/python3 /usr/local/bin/python\n'
(root / 'hosting' / 'Dockerfile.cloud').write_text(source_stage + dockerfile)
(root / 'hosting' / 'toolkit-revision').write_text(revision + '\n')
